#!/usr/bin/env bash
# ==============================================================================
# PostPulse Canary Traffic Promotion Script
# Usage: ./canary-promote.sh <PERCENTAGE> (e.g. 10, 25, 50, 100)
# ==============================================================================

set -euo pipefail

TARGET_PERCENT="${1:-10}"
ROUTER_CONTAINER="canary-router"
CANARY_CONTAINER="canary-backend-canary"
NGINX_CONF_PATH="deploy/canary/nginx.canary.conf"

echo "=========================================================="
echo "🚀 PostPulse Canary Promotion Protocol"
echo "Target Canary Traffic: ${TARGET_PERCENT}%"
echo "=========================================================="

# 1. Input Validation
if ! [[ "$TARGET_PERCENT" =~ ^[0-9]+$ ]] || [ "$TARGET_PERCENT" -lt 0 ] || [ "$TARGET_PERCENT" -gt 100 ]; then
  echo "❌ Error: Target percentage must be an integer between 0 and 100."
  exit 1
fi

STABLE_PERCENT=$((100 - TARGET_PERCENT))

# 2. Pre-promotion Health Check on Canary Instance
echo "🔍 Step 1: Performing health verification on candidate canary..."
if command -v docker &> /dev/null && docker ps -q -f name="${CANARY_CONTAINER}" | grep -q .; then
  CANARY_HTTP_CODE=$(docker exec "${CANARY_CONTAINER}" curl -s -o /dev/null -w "%{http_code}" http://localhost:3000/api/health || echo "000")
  if [ "$CANARY_HTTP_CODE" != "200" ]; then
    echo "❌ ABORTING: Canary instance health check returned HTTP ${CANARY_HTTP_CODE}. Promotion cancelled."
    exit 1
  fi
  echo "✓ Canary container is HEALTHY (HTTP 200)."
else
  echo "ℹ Docker container not detected in current shell; updating local/API routing state."
fi

# 3. Update Nginx Upstream Configuration File
echo "⚙ Step 2: Updating Nginx upstream weights (Stable: ${STABLE_PERCENT}%, Canary: ${TARGET_PERCENT}%)..."
if [ -f "$NGINX_CONF_PATH" ]; then
  cat <<EOF > "$NGINX_CONF_PATH"
# PostPulse Canary Traffic Router Configuration
# Auto-generated by canary-promote.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")

upstream postpulse_backend {
    server backend-stable:3000 weight=${STABLE_PERCENT} max_fails=3 fail_timeout=10s;
    server backend-canary:3000 weight=${TARGET_PERCENT} max_fails=3 fail_timeout=10s;
}

server {
    listen 80;
    server_name localhost;

    root /usr/share/nginx/html;
    index index.html;

    add_header X-Proxy-Router "PostPulse-Canary-Engine/1.0" always;

    location /api/ {
        proxy_pass http://postpulse_backend;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;

        add_header X-Upstream-Backend \$upstream_addr always;
        add_header X-Upstream-Response-Time \$upstream_response_time always;
    }

    location / {
        try_files \$uri \$uri/ /index.html;
    }

    location /healthz {
        access_log off;
        return 200 '{"router": "healthy", "canary_weight": ${TARGET_PERCENT}, "stable_weight": ${STABLE_PERCENT}}';
        add_header Content-Type application/json;
    }
}
EOF
fi

# 4. Reload Nginx Router Container (if running)
if command -v docker &> /dev/null && docker ps -q -f name="${ROUTER_CONTAINER}" | grep -q .; then
  echo "🔄 Reloading Nginx configuration inside ${ROUTER_CONTAINER} with zero downtime..."
  docker exec "${ROUTER_CONTAINER}" nginx -s reload
  echo "✓ Nginx reloaded successfully."
fi

# 5. Notify Application Controller Endpoint (if running)
API_HOST="${APP_HOST:-http://localhost:3000}"
curl -s -X POST "${API_HOST}/api/canary/traffic-split" \
  -H "Content-Type: application/json" \
  -d "{\"percentage\": ${TARGET_PERCENT}}" > /dev/null || true

echo "=========================================================="
echo "🎉 Canary Promotion Complete!"
echo "Active Traffic Distribution: ${STABLE_PERCENT}% Stable / ${TARGET_PERCENT}% Canary"
echo "=========================================================="
